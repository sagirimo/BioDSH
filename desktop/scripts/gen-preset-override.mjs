// 生成 BioDSH 对 dsh 随附 `standard` 智能体预设的覆盖模板(dsh >= 0.2)。
// 背景:0.2 起智能体平面(人设、技能目录、工具)都在 agent preset 里;覆盖 preset 必须重述完整 config
// (官方 editing-cordis-compositions 技能的规定),手抄插件清单会随 dsh 升级失效。所以打包时从已安装的
// dsh-web-app/presets/standard.patch.yml 读出原样声明,只把两处换成占位符:
//   persona.prefix                    → __BIODSH_PERSONA__
//   skill-filesystem.customSkillDirs  → [__BIODSH_OFFICIAL_SKILLS__]
// 输出单行 YAML flow 映射(保留 `!!js` 标签,平台判断仍由 Loader 运行时求值),dsh.rs 只做字符串替换
// (占位符换成 JSON 字符串,JSON 字符串是合法的 YAML 双引号标量),Rust 侧不必解析 YAML。
// 用法:node scripts/gen-preset-override.mjs [runtimeDir]   (默认 desktop/dsh-runtime;写 <runtimeDir>/node_modules/@biodsh/preset-standard.yml)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

export function genPresetOverride(runtimeDir = path.join(here, '..', 'dsh-runtime')) {
  runtimeDir = path.resolve(runtimeDir);
  const src = path.join(runtimeDir, 'node_modules', '@deepseek-ai', 'dsh-web-app', 'presets', 'standard.patch.yml');
  if (!existsSync(src)) { console.log(`[gen-preset-override] 跳过:找不到 ${src}(dsh < 0.2?)`); return false; }
  const YAML = createRequire(path.join(runtimeDir, 'package.json'))('yaml');
  const JS = Symbol('js');
  const rows = YAML.parse(readFileSync(src, 'utf8'), { customTags: [{ tag: 'tag:yaml.org,2002:js', resolve: (s) => ({ [JS]: s }) }] });
  const row = rows[0].insert.find((r) => r.id === 'preset-standard');
  if (!row) throw new Error('preset-standard declaration not found in ' + src);
  const plugin = (id) => {
    const p = row.config.plugins.find((x) => x.id === id);
    if (!p) throw new Error(`preset-standard has no ${id} row`);
    return (p.config ??= {});
  };
  plugin('persona').prefix = '__BIODSH_PERSONA__';
  plugin('skill-filesystem').customSkillDirs = ['__BIODSH_OFFICIAL_SKILLS__'];
  plugin('tool-skill');
  // 单行 flow 序列化:普通值用 JSON(合法 YAML),`!!js` 值原样带标签;占位符输出为裸词供 dsh.rs 替换
  const ser = (v) => v && typeof v === 'object' && JS in v ? `!!js ${JSON.stringify(v[JS])}`
    : Array.isArray(v) ? `[${v.map(ser).join(', ')}]`
    : v && typeof v === 'object' ? `{${Object.entries(v).map(([k, x]) => `${JSON.stringify(k)}: ${ser(x)}`).join(', ')}}`
    : typeof v === 'string' && /^__BIODSH_[A-Z_]+__$/.test(v) ? v : JSON.stringify(v);
  const line = ser(row);
  const ver = JSON.parse(readFileSync(path.join(runtimeDir, 'node_modules', '@deepseek-ai', 'dsh', 'package.json'), 'utf8')).version;
  // 放进 node_modules/@biodsh/ 下:打包资源只收 dsh-runtime/node_modules(tauri.conf resources)
  const out = path.join(runtimeDir, 'node_modules', '@biodsh', 'preset-standard.yml');
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, `# generated by desktop/scripts/gen-preset-override.mjs from dsh ${ver} dsh-web-app/presets/standard.patch.yml\n- ${line}\n`);
  console.log(`[gen-preset-override] 写入 ${out}`);
  return true;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) genPresetOverride(process.argv[2]);
