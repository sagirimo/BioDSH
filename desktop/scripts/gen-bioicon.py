"""Regenerate BioIcon.tsx from the Sky SVG masters (the shipped adapter dropped rect width/height)."""
import re, sys, xml.etree.ElementTree as ET
from pathlib import Path
kit = Path(sys.argv[1]); out = Path(sys.argv[2])
NS = '{http://www.w3.org/2000/svg}'
def camel(a): return re.sub(r'-([a-z])', lambda m: m.group(1).upper(), a)
def attrs(el, skip=()):
    return ''.join(f' {camel(k)}="{v}"' for k, v in el.attrib.items() if k not in skip)
def node(el):
    tag = el.tag.replace(NS, '')
    inner = ''.join(node(c) for c in el)
    return f'<{tag}{attrs(el)}>{inner}</{tag}>' if inner else f'<{tag}{attrs(el)} />'
groups = [('icons/ui', 'ui'), ('icons/domain', 'domain'), ('icons/file', 'file'), ('illustrations', 'illustrations')]
lines = []
for d, prefix in groups:
    for f in sorted((kit / d).glob('*.svg')):
        root = ET.parse(f).getroot()
        body = ''.join(node(c) for c in root)
        g = attrs(root, skip=('width', 'height', 'viewBox', 'xmlns'))
        lines.append(f'  "{prefix}-{f.stem}": {{ viewBox: "{root.get("viewBox")}", body: (<g{g}>{body}</g>) }},')
src = (kit / 'react/BioIcon.tsx').read_text('utf-8')
head = src[:src.index('const assets = {') + len('const assets = {')]
tail = src[src.index('} as const;'):]
head = head.replace('// Generated by build.py.', '// Generated from the SVG masters by gen_bioicon.py (keeps rect width/height).')
out.write_text(head + '\n' + '\n'.join(lines) + '\n' + tail, 'utf-8')
print(len(lines), 'assets')
